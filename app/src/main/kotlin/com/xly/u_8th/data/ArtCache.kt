package com.xly.u_8th.data

import android.content.Context
import android.net.Uri
import androidx.core.net.toUri
import com.xly.u_8th.domain.Song
import com.xly.u_8th.util.fnv1a
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import java.util.concurrent.ConcurrentHashMap

/**
 * Disk caches for album art.
 *
 * Two layers, mirroring the previous app's layout so existing cache files
 * keep resolving:
 * - Notification/temp art: `cacheDir/art_<fnv1a(playUri) 8hex>.img`, pruned
 *   to the ~100 most recent files (podar se amortiza cada 25 escrituras).
 * - Album art cache: `app_support/art_cache/<albumKey>.img` (regenerated by
 *   scrolling, cleared from the info dialog).
 */
class ArtCache(private val context: Context) {

    private val tempDir: File get() = context.cacheDir

    // Same dir the previous version used (path_provider "app_support").
    private val supportDir: File by lazy { context.getDir("app_support", Context.MODE_PRIVATE) }

    // ---- Temp art (notification / lock screen) ----

    /** Returns a file URI with the song's art, or the MediaStore artUri. */
    suspend fun getArtUri(song: Song): Uri? = withContext(Dispatchers.IO) {
        val cacheKey = song.playUri
        tempArtFiles[cacheKey]?.let { cached ->
            if (cached.exists()) return@withContext Uri.fromFile(cached)
            tempArtFiles.remove(cacheKey)
        }
        val art = song.albumArt
        if (art != null && art.isNotEmpty()) {
            try {
                val stable = fnv1a(cacheKey).toString(16).padStart(8, '0')
                val file = File(tempDir, "art_$stable.img")
                if (!file.exists()) {
                    file.writeBytes(art)
                    tempArtFiles[cacheKey] = file
                    maybePruneTempArt()
                } else {
                    tempArtFiles[cacheKey] = file
                }
                return@withContext Uri.fromFile(file)
            } catch (_: Exception) {
            }
        }
        // Fallback: MediaStore cover URI (readable in-process).
        song.albumArtUri?.takeIf { it.isNotEmpty() }?.let {
            return@withContext it.toUri()
        }
        null
    }

    // getArtUri se llama desde varias coroutines (el servicio lanza una por
    // cambio de pista): un HashMap plano sufriría carreras.
    private val tempArtFiles = ConcurrentHashMap<String, File>()

    /** Escrituras desde la última poda. */
    private val writesSincePrune = java.util.concurrent.atomic.AtomicInteger()

    /**
     * Podar es un listado + orden del directorio completo: hacerlo en cada
     * escritura nueva era O(n log n) por canción. Se dispara solo al
     * superar el margen por encima del tope.
     */
    private suspend fun maybePruneTempArt() {
        if (writesSincePrune.incrementAndGet() < PRUNE_EVERY) return
        writesSincePrune.set(0)
        pruneTempArt()
    }

    /** Keeps at most [TEMP_ART_LIMIT] recent `art_*.img` files. */
    suspend fun pruneTempArt() = withContext(Dispatchers.IO) {
        try {
            val legacy = tempDir.listFiles { f -> f.name.startsWith("art_") && f.name.endsWith(".png") }
            legacy?.forEach { runCatching { it.delete() } }
            val files = tempDir.listFiles { f -> f.name.startsWith("art_") && f.name.endsWith(".img") }
                ?.sortedBy { it.lastModified() } ?: return@withContext
            if (files.size > TEMP_ART_LIMIT) {
                // Los más antiguos salen primero y salen del mapa: si no, la
                // siguiente getArtUri los volvería a "encontrar".
                for (f in files.take(files.size - TEMP_ART_LIMIT)) {
                    runCatching { f.delete() }
                    tempArtFiles.entries.removeIf { it.value == f }
                }
            }
        } catch (_: Exception) {
        }
    }

    private companion object {
        const val TEMP_ART_LIMIT = 100
        const val PRUNE_EVERY = 25
    }

    // ---- Album art cache ----

    private fun albumKeyOld(album: String): String =
        album.lowercase().trim().replace(Regex("[^a-z0-9]+"), "_")

    /**
     * Stable key including the artist to avoid cross-artist collisions.
     * Artista y álbum van separados por U+001F: concatenados sin más,
     * ("ab", "c") y ("a", "bc") daban la misma clave.
     */
    fun albumKey(album: String, artist: String? = null): String =
        keyFor(album, artist, separator = "\u001F")

    /** Formato anterior (sin separador): solo para migrar ficheros ya cacheados. */
    private fun albumKeyV1(album: String, artist: String?): String =
        keyFor(album, artist, separator = "")

    private fun keyFor(album: String, artist: String?, separator: String): String {
        val a = album.lowercase().trim()
        val ar = artist?.lowercase()?.trim() ?: ""
        val combined = if (ar.isEmpty()) a else "$ar$separator$a"
        val safe = combined.replace(Regex("[^a-z0-9]+"), "_")
        val trimmed = if (safe.length > 60) safe.substring(0, 60) else safe
        val hash = fnv1a(combined).toString(16).padStart(8, '0').substring(0, 6)
        return "${trimmed}_$hash"
    }

    private fun artCacheDir(): File? = try {
        File(supportDir, "art_cache").apply { if (!exists()) mkdirs() }
    } catch (_: Exception) {
        null
    }

    suspend fun cacheAlbumArt(album: String, bytes: ByteArray, artist: String? = null) =
        withContext(Dispatchers.IO) {
            try {
                val dir = artCacheDir() ?: return@withContext
                if (bytes.isEmpty()) return@withContext
                File(dir, "${albumKey(album, artist)}.img").writeBytes(bytes)
            } catch (_: Exception) {
            }
        }

    suspend fun loadCachedAlbumArt(album: String, artist: String? = null): ByteArray? =
        withContext(Dispatchers.IO) {
            try {
                val dir = artCacheDir() ?: return@withContext null
                val current = File(dir, "${albumKey(album, artist)}.img")
                if (current.exists()) {
                    val bytes = current.readBytes()
                    if (bytes.isNotEmpty()) return@withContext bytes
                }
                // Migración: clave anterior sin separador; se renombra para
                // no volver a extraer la portada.
                val v1 = File(dir, "${albumKeyV1(album, artist)}.img")
                if (v1 != current && v1.exists()) {
                    val bytes = v1.readBytes()
                    if (bytes.isNotEmpty()) {
                        if (!v1.renameTo(current)) runCatching { current.writeBytes(bytes); v1.delete() }
                        return@withContext bytes
                    }
                }
                // Migration: try the old album-only key format once.
                val legacyFile = File(dir, "${albumKeyOld(album)}.img")
                if (legacyFile.exists()) {
                    val bytes = legacyFile.readBytes()
                    if (bytes.isNotEmpty()) return@withContext bytes
                }
                null
            } catch (_: Exception) {
                null
            }
        }

    /** Deletes the regenerable disk art cache; returns the number of files removed. */
    suspend fun clearArtCache(): Int = withContext(Dispatchers.IO) {
        try {
            val dir = artCacheDir() ?: return@withContext 0
            if (!dir.exists()) return@withContext 0
            var n = 0
            dir.listFiles()?.forEach { f ->
                if (f.isFile) {
                    runCatching { if (f.delete()) n++ }
                }
            }
            n
        } catch (_: Exception) {
            0
        }
    }
}
